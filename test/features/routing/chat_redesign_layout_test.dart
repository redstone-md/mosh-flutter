ScriptableGateway _gateway() {
  final now = BigInt.from(DateTime(2026, 10, 1, 14, 32).millisecondsSinceEpoch);
  return ScriptableGateway()
    ..seedSessions([
      TestSnapshots.dm(sessionId: 'alice', peerDisplayName: 'Alice', messages: [
        TestMessages.dm(
            fromDevice: 'Alice',
            body: 'Привет! Проверим, что всё работает.',
            sentAtMs: now),
        TestMessages.dm(
            fromDevice: 'me',
            body: 'Да, отлично. Сейчас отправлю файл.',
            attachment: testAttachment(attachmentId: 'sample-file'),
            sentAtMs: now + BigInt.one),
      ])
    ])
    ..seedGroups([
      TestSnapshots.group(
          groupId: 'crew',
          label: 'Design team',
          deviceFingerprint: 'self',
          inviteUri: 'mosh-group://crew',
          messages: [
            TestMessages.group(
                fromDevice: 'Alice',
                fromFingerprint: 'alice',
                body: 'Привет! Проверим, что всё работает.',
                sentAtMs: now),
            TestMessages.group(
                fromDevice: 'me',
                fromFingerprint: 'self',
                body: 'Да, отлично. Сейчас отправлю файл.',
                sentAtMs: now + BigInt.one),
            TestMessages.group(
                fromDevice: 'Bob',
                fromFingerprint: 'bob',
                body: 'Отлично, проверим права доступа для нового участника.',
                sentAtMs: now + BigInt.two),
          ])
    ])
    ..seedChannels([
      TestSnapshots.channel(
          name: 'general',
          deviceFingerprint: 'self',
          messages: [
            TestMessages.channel(
                fromDevice: 'Bob',
                fromFingerprint: 'bob',
                body: 'Новости проекта',
                sentAtMs: now),
          ])
    ]);
}

Future<void> _open(WidgetTester tester, String title) async {
  await tester.tap(find.descendant(
      of: find.byType(SessionsScreen), matching: find.text(title)));
  await tester.pumpAndSettle();
}

/// Optional exports for manual visual inspection, never generated by normal CI.
Future<void> _screenshot(WidgetTester tester, String name) async {
  const directory = String.fromEnvironment('MOSH_REDESIGN_SCREENSHOTS');
  if (directory.isEmpty) return;
  final boundary = tester
      .firstRenderObject<RenderRepaintBoundary>(find.byType(RepaintBoundary));
  await tester.runAsync(() async {
    final image = await boundary.toImage();
    final data = await image.toByteData(format: ui.ImageByteFormat.png);
    await Directory(directory).create(recursive: true);
    await File('$directory/$name.png').writeAsBytes(data!.buffer.asUint8List());
    image.dispose();
  });
}

void main() {
  setUp(() {
    const channel = MethodChannel('com.llfbandit.record/messages');
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
        .setMockMethodCallHandler(channel, (call) async => null);
    addTearDown(() => TestDefaultBinaryMessengerBinding
        .instance.defaultBinaryMessenger
        .setMockMethodCallHandler(channel, null));
  });
  setUpAll(() async {
    const font = String.fromEnvironment('MOSH_REDESIGN_FONT');
    if (font.isEmpty) return;
    final bytes = ByteData.sublistView(await File(font).readAsBytes());
    for (final name in ['Inter Tight', 'Inter', 'Roboto', 'monospace']) {
      await (FontLoader(name)..addFont(Future.value(bytes))).load();
    }
    final icons = await rootBundle.load('fonts/MaterialIcons-Regular.otf');
    await (FontLoader('MaterialIcons')..addFont(Future.value(icons))).load();
  });
  for (final width in [320.0, 390.0, 581.0, 800.0, 1280.0, 1536.0]) {
    for (final title in ['Alice', 'Design team', '#general']) {
      testWidgets(
          '$title at ${width.toInt()}px: responsive details and usable chat',
          (tester) async {
        await pumpShellApp(tester,
            gateway: _gateway(), physical: Size(width, 900));
        await _open(tester, title);
        if (width >= 1280) {
          expect(find.byKey(const ValueKey('conversation-details-docked')),
              findsOneWidget);
          expect(find.byType(PeerStatusDrawer), findsNothing);
          if (width == 1536) {
            await _screenshot(
                tester,
                title == 'Design team'
                    ? 'desktop-group'
                    : 'desktop-${title == 'Alice' ? 'dm' : 'channel'}');
          }
          await tester.tap(find.descendant(
              of: find.byType(ConversationDetailsPanel),
              matching: find.byIcon(Icons.close)));
          await tester.pumpAndSettle();
          expect(find.byType(ConversationDetailsPanel), findsNothing);
          await tester.tap(find.byTooltip('Conversation details'));
          await tester.pumpAndSettle();
          expect(find.byKey(const ValueKey('conversation-details-docked')),
              findsOneWidget);
        } else {
          expect(find.byType(ConversationDetailsPanel), findsNothing);
          if (width == 390) {
            await _screenshot(
                tester,
                'mobile-${title == 'Alice' ? 'dm' : title == 'Design team' ? 'group' : 'channel'}');
          }
          await tester.tap(find.byTooltip('Conversation details'));
          await tester.pumpAndSettle();
          expect(find.byType(PeerStatusDrawer), findsOneWidget);
          expect(find.byType(ConversationDetailsPanel), findsOneWidget);
          await tester.sendKeyEvent(LogicalKeyboardKey.escape);
          await tester.pumpAndSettle();
          expect(find.byType(ConversationDetailsPanel), findsNothing);
        }
      });
    }
  }

  testWidgets(
      'Ctrl+K focuses the list from an active chat and returns to mobile list',
      (tester) async {
    for (final width in [1536.0, 390.0]) {
      await pumpShellApp(tester,
          gateway: _gateway(), physical: Size(width, 900));
      await _open(tester, 'Alice');
      await tester.tap(find.widgetWithText(TextField, 'Write a message…'));
      await tester.sendKeyDownEvent(LogicalKeyboardKey.controlLeft);
      await tester.sendKeyEvent(LogicalKeyboardKey.keyK);
      await tester.sendKeyUpEvent(LogicalKeyboardKey.controlLeft);
      await tester.pumpAndSettle();
      final search = tester
          .widget<TextField>(find.byKey(const ValueKey('chat-list-search')));
      expect(search.focusNode!.hasFocus, isTrue);
      if (width <= 580) {
        expect(appRouter.routeInformationProvider.value.uri.path,
            AppRoutes.sessions);
      }
    }
  });
}
